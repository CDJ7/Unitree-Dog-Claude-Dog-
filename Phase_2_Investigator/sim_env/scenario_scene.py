from sim_env.spatter.generator import GENERATOR_VERSION
from sim_env.spatter.mj_surfaces import MjSurfaces

HERE = Path(__file__).resolve().parent
BUILD = HERE / "build" / "scenarios"
SCENE_VERSION = "1"

BLOOD_RGB = (0.42, 0.02, 0.03)
MANNEQUIN_RGBA = "0.80 0.78 0.73 1"
PREFIX_MANNEQUIN = "mq_"
PREFIX_PROP = "prop_"
PREFIX_DISTRACTOR = "distractor_"
PREFIX_STAIN = "stain_"

ASSETS = f"""
<material name="csi_blood" rgba="{BLOOD_RGB[0]} {BLOOD_RGB[1]} {BLOOD_RGB[2]} 1" specular="0.35" shininess="0.6"/>
<material name="csi_mannequin" rgba="{MANNEQUIN_RGBA}" specular="0.05"/>
<material name="csi_prop" rgba="0.45 0.45 0.48 1" specular="0.1"/>
"""


def _f(v):
    return " ".join(f"{float(x):.5g}" for x in np.ravel(v))


def load_scenario_config(spec):
    path = resolve_scenario(spec)
    scn = yaml.safe_load(Path(path).read_text())
    scn.setdefault("_path", str(path))
    return scn


