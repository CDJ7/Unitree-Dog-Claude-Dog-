def mannequin_parts(height=1.75, posture="standing"):
    """Capsule stick figure in its local frame, scaled to `height`: [(type, coords, radius)]."""
    k = height / 1.75
    if posture not in POSTURES:
        raise ValueError(f"posture {posture!r}: choose {list(POSTURES)}")
    out = []
    for typ, p, r in POSTURES[posture]:
        out.append((typ, np.asarray(p, float) * k, r * k))
    return out


def _to_world(p, x, y, yaw, z=0.0):
    c, s = np.cos(yaw), np.sin(yaw)
    q = np.asarray(p, float).reshape(-1, 3)
    w = np.column_stack([x + c * q[:, 0] - s * q[:, 1], y + s * q[:, 0] + c * q[:, 1], z + q[:, 2]])
    return w.ravel()


def mannequin_xml(m, posture=None):
    posture = posture or m.get("posture", "standing")
    yaw = np.radians(m.get("yaw_deg", 0.0))
    x, y = m["position"][:2]
    geoms = []
    for i, (typ, p, r) in enumerate(mannequin_parts(m.get("height", 1.75), posture)):
        w = _to_world(p, x, y, yaw)
        name = f"{PREFIX_MANNEQUIN}{m['id']}_{i}"
        if typ == "sphere":
            geoms.append(f'<geom name="{name}" type="sphere" pos="{_f(w)}" size="{r:.4g}" material="csi_mannequin" group="0"/>')
        else:
            geoms.append(f'<geom name="{name}" type="capsule" fromto="{_f(w)}" size="{r:.4g}" material="csi_mannequin" group="0"/>')
    return f'<body name="{PREFIX_MANNEQUIN}{m["id"]}">' + "".join(geoms) + "</body>"


# ---------------------------------------------------------------- other props
def _box_or_cyl(name, item, rgba, z_base=0.0):
    kind = item.get("shape") or ("cylinder" if item.get("kind") in ("mug", "basket", "bin", "vase", "cylinder") else "box")
    yaw = np.radians(item.get("yaw_deg", 0.0))
    quat = f"{np.cos(yaw / 2):.6g} 0 0 {np.sin(yaw / 2):.6g}"
    c = list(item["center"])
    if kind == "cylinder":
        r, h = item.get("radius", 0.1), item.get("height", 0.2)
        z = c[2] if len(c) > 2 else z_base + h / 2
        return (f'<geom name="{name}" type="cylinder" pos="{c[0]:.4g} {c[1]:.4g} {z:.4g}" size="{r:.4g} {h / 2:.4g}" '
                f'rgba="{rgba}" group="0" quat="{quat}"/>')
    sx, sy, sz = item["size"]
    z = c[2] if len(c) > 2 else z_base + sz / 2
    return (f'<geom name="{name}" type="box" pos="{c[0]:.4g} {c[1]:.4g} {z:.4g}" size="{sx / 2:.4g} {sy / 2:.4g} {sz / 2:.4g}" '
            f'rgba="{rgba}" group="0" quat="{quat}"/>')


def props_xml(scn):
    parts = []
    for m in scn.get("mannequins", []) or []:
        if m.get("present", True):
            parts.append(mannequin_xml(m))
    for o in scn.get("obstacles", []) or []:
        rgba = " ".join(map(str, o.get("color", [0.45, 0.45, 0.48]))) + " 1"
        parts.append(_box_or_cyl(f"{PREFIX_PROP}{o['id']}", o, rgba))
    for d in scn.get("distractors", []) or []:
        rgba = " ".join(map(str, d.get("color", [0.75, 0.06, 0.08]))) + " 1"
        parts.append(_box_or_cyl(f"{PREFIX_DISTRACTOR}{d['id']}", d, rgba))
    return "".join(parts)


# --------------------------------------------------------------------- stains
def _frame(direction, normal):
    n = np.asarray(normal, float)
    n /= np.linalg.norm(n)
    x = np.asarray(direction, float) - (np.asarray(direction, float) @ n) * n
    if np.linalg.norm(x) < 1e-9:
        x = np.cross(n, [0, 0, 1]) if abs(n[2]) < 0.9 else np.cross(n, [0, 1, 0])
    x /= np.linalg.norm(x)
    y = np.cross(n, x)
    R = np.column_stack([x, y, n])
    q = np.zeros(4)
    mujoco.mju_mat2Quat(q, R.ravel())
    return q, n


def _ellipsoid(name, center, quat, a, b, rgba, normal, lift=0.0008, thick=0.0003):
    pos = np.asarray(center, float) + lift * np.asarray(normal)
    return (f'<geom name="{name}" type="ellipsoid" pos="{_f(pos)}" quat="{_f(quat)}" '
            f'size="{max(a, 2e-4):.5g} {max(b, 2e-4):.5g} {thick:.5g}" material="csi_blood" rgba="{rgba}" '
            f'group="1" contype="0" conaffinity="0"/>')


def stain_geoms(gt, tails=True, rng=None):
    """XML for every stain and smear in the ground truth (list of strings)."""
    rng = rng or np.random.default_rng(0)
    normals = {s["id"]: np.array(s["normal"]) for s in gt["surfaces"]}
    out = []
    for st in gt["stains"]:
        n = normals[st["surface_id"]]
        q, n = _frame(st["dir_world"], n)
        shade = rng.uniform(0.75, 1.15)
        rgba = f"{BLOOD_RGB[0] * shade:.3f} {BLOOD_RGB[1] * shade:.3f} {BLOOD_RGB[2] * shade:.3f} 1"
        out.append(_ellipsoid(f"{PREFIX_STAIN}{st['id']}", st["center_world"], q, st["length"] / 2, st["width"] / 2, rgba, n))
        if tails and st.get("tail_length", 0) > 0.0005:
            d = np.asarray(st["dir_world"])
            tl = st["tail_length"]
            c = np.asarray(st["center_world"]) + d * (st["length"] / 2 + tl / 2 - 0.1 * st["width"])
            out.append(_ellipsoid(f"{PREFIX_STAIN}{st['id']}_tail", c, q, tl / 2 + 0.1 * st["width"],
                                  0.18 * st["width"], rgba, n, lift=0.0007))
    for sm in gt["smears"]:
        n = normals[sm["surface_id"]]
        pts = np.asarray(sm["path_world"], float)
        w = sm["width"]
        n_feather = int(len(pts) * (1 - sm.get("feather_frac", 0.3)))
        for i in range(len(pts) - 1):
            a, b = pts[i], pts[i + 1]
            seg = b - a
            L = np.linalg.norm(seg)
            if L < 1e-6:
                continue
            q, nn = _frame(seg, n)
            mid = (a + b) / 2
            if i < n_feather:
                out.append(_ellipsoid(f"{PREFIX_STAIN}{sm['id']}_{i}", mid, q, L * 0.8, w / 2,
                                      f"{BLOOD_RGB[0]:.3f} {BLOOD_RGB[1]:.3f} {BLOOD_RGB[2]:.3f} 1", nn))
            else:                       # feathered end: separate streaks
                side = np.cross(nn, seg / L)
                for j, off in enumerate((-0.33, 0.0, 0.33)):
                    if rng.random() < 0.25:
                        continue
                    out.append(_ellipsoid(f"{PREFIX_STAIN}{sm['id']}_{i}_{j}", mid + side * off * w, q, L * 0.7,
                                          w * 0.08, f"{BLOOD_RGB[0]:.3f} {BLOOD_RGB[1]:.3f} {BLOOD_RGB[2]:.3f} 1", nn))
    return out


# ---------------------------------------------------------------------- build
def _hash(scn):
    src = {k: v for k, v in scn.items() if not k.startswith("_")}
    files = [HERE / "spatter" / f for f in ("mechanisms.py", "physics.py", "stains.py", "mj_surfaces.py", "generator.py")]
    h = hashlib.sha1(json.dumps(src, sort_keys=True, default=str).encode())
    h.update(SCENE_VERSION.encode() + GENERATOR_VERSION.encode())
    for f in files + [Path(__file__)]:
        h.update(f.read_bytes())
    return h.hexdigest()[:16]


def _props_patch(scn):
    xml = props_xml(scn)

    def patch(path):
        def fn(root):
            append_xml(root, "asset", ASSETS)
            append_xml(root, "worldbody", xml)
        patch_file(path, fn)
    return patch


def resolve_auto_heights(scn):
    """Place props marked `z: auto` on whatever visible surface is below them (a bare scene)."""
    items = [it for key in ("distractors", "obstacles") for it in (scn.get(key) or []) if it.get("z") == "auto"]
    if not items:
        return scn
    scn = copy.deepcopy(scn)
    items = [it for key in ("distractors", "obstacles") for it in (scn.get(key) or []) if it.get("z") == "auto"]
    sim = SimSession(scn["environment"])
    try:
        surf = MjSurfaces(sim.model, sim.data, exclude_geoms=sim.robot_geoms)
        for it in items:
            x, y = it["center"][:2]
            t, _ = surf.cast([x, y, 3.0], [0, 0, -3.5])
            top = 3.0 - 3.5 * t if t is not None else 0.0
            h = it["height"] if "radius" in it else it["size"][2]
            it["center"] = [x, y, round(top + h / 2 + 0.001, 4)]
            it["z"] = round(top, 4)
    finally:
        sim.close()
    return scn


def _snap_satellites(gt, surfaces):
    kept, dropped = [], 0
    normals = {r.id: r.normal for r in surfaces.rects}
    for st in gt["stains"]:
        if st["kind"] == "satellite":
            p = surfaces.snap(st["center_world"], normals[st["surface_id"]], st["surface_id"])
            if p is None:
                dropped += 1
                continue
            st["center_world"] = p.tolist()
        kept.append(st)
    gt["stains"] = kept
    for sm in gt["smears"]:
        n = normals[sm["surface_id"]]
        snapped = []
        for p in sm["path_world"]:
            q = surfaces.snap(p, n, sm["surface_id"])
            snapped.append((q if q is not None else np.asarray(p)).tolist())
        sm["path_world"] = snapped
    return dropped


def build_scenario(scn, force=False, verbose=True):
    """Generate (or load from cache) ground truth + scene fragments. Returns the build dir."""
    out = BUILD / scn["id"]
    digest = _hash(scn)
    meta_path = out / "meta.json"
    if not force and meta_path.exists() and json.loads(meta_path.read_text()).get("hash") == digest:
        return out
    if verbose:
        print(f"[scenario] building {scn['id']} (spatter landing on the real scene)...", flush=True)
    scn = resolve_auto_heights(scn)
    sim = SimSession(scn["environment"], scene_patch=_props_patch(scn), spawn=scn.get("spawn"))
    try:
        m = sim.model
        exclude = set(sim.robot_geoms)
        exclude |= {g for g in range(m.ngeom)
                    if (mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_GEOM, g) or "").startswith(PREFIX_MANNEQUIN)}
        surfaces = MjSurfaces(m, sim.data, exclude_geoms=exclude)
        gt = generate(scn, surfaces=surfaces)
        dropped = _snap_satellites(gt, surfaces)
        gt["surfaces"] = surfaces.to_dict()
    finally:
        sim.close()
    gt.update(environment=scn["environment"], spawn=scn.get("spawn"),
              distractors=scn.get("distractors", []) or [], mannequins=scn.get("mannequins", []) or [],
              obstacles=scn.get("obstacles", []) or [], scene_version=SCENE_VERSION,
              satellites_dropped_off_edges=dropped)
    gt["clusters"] = stain_clusters(gt)
    out.mkdir(parents=True, exist_ok=True)
    save_ground_truth(gt, out / "ground_truth.json")
    (out / "props.xml").write_text(props_xml(scn))
    (out / "stains.xml").write_text("\n".join(stain_geoms(gt)))
    (out / "scenario.yaml").write_text(yaml.safe_dump({k: v for k, v in scn.items() if not k.startswith("_")},
                                                      sort_keys=False))
    meta_path.write_text(json.dumps({"hash": digest, "n_stains": len(gt["stains"]),
                                     "n_smears": len(gt["smears"]), "n_clusters": len(gt["clusters"])}))
    if verbose:
        n_land = sum(d["landed"] for d in gt["droplets"])
        print(f"[scenario] {len(gt['droplets'])} droplets ({n_land} landed), {len(gt['stains'])} stains, "
              f"{len(gt['smears'])} smears, {len(gt['clusters'])} clusters -> {out}", flush=True)
    return out


def scenario_patch(build_dir, show_stains=True, extra=None):
    build_dir = Path(build_dir)
    worldbody = (build_dir / "props.xml").read_text()
    if show_stains:
        worldbody += (build_dir / "stains.xml").read_text()

    def patch(path):
        def fn(root):
            append_xml(root, "asset", ASSETS)
            append_xml(root, "worldbody", worldbody)
            if extra:
                extra(root)
        patch_file(path, fn)
    return patch


def open_scenario(scn, show_stains=True, spawn=None, extra=None, force=False, **session_kwargs):
    """(SimSession, ground truth) for a scenario config dict."""
    out = build_scenario(scn, force=force)
    gt = json.loads((out / "ground_truth.json").read_text())
    sim = SimSession(scn["environment"], scene_patch=scenario_patch(out, show_stains, extra),
                     spawn=spawn if spawn is not None else scn.get("spawn"), **session_kwargs)
    sim.scenario_id = scn["id"]
    return sim, gt


def with_overrides(scn, **kw):
    s = copy.deepcopy(scn)
    s.update(kw)
    return s
