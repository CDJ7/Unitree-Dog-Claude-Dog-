"""Build a crime-scene scenario into the simulator: props, spatter, stains, ground truth.

    sim, gt = open_scenario(load_scenario_config(1))      # SimSession + ground truth dict

Steps (cached in sim_env/build/scenarios/<id>/, rebuilt when the config or
generator changes):
1. Props: mannequins (capsule stick figures), obstacles and red distractor
   objects are added to the environment (group 0: seen by camera, LiDAR and
   depth; they collide with the robot).
2. Spatter: the scenario's events are generated by the physics-based
   generator, landing on the real scene through MuJoCo ray casting
   (`spatter.mj_surfaces.MjSurfaces`). Satellites are snapped onto the real
   surface; those that would hang off an edge are dropped.
3. Stains: every stain is drawn as geometry, not a texture (MuJoCo 3.3.7
   drops texture alpha): a flattened red ellipsoid of exactly the ground-truth
   width, length and orientation, 0.8 mm off the surface, plus a narrow tail
   ellipsoid downstream; smears are chains of flat ellipsoids that break into
   streaks. Group 1, no contacts, so LiDAR and depth do not see them.
4. Ground truth JSON: events (origin, mechanism, weapon category, swing path),
   every droplet and stain, mannequins, obstacles, distractors, stain
   clusters (inspection targets), environment and spawn.
"""
